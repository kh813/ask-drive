defmodule AskDrive.ClientCerts.InstallGuide do
  @moduledoc """
  How to install an AskDrive client certificate (.p12), per OS / browser (spec 6.14) —
  shown on the page a device without a certificate gets, where the person who needs it is.
  Menu names differ between OS versions and device makers; the wording says so. Every
  way installs into the user's own store: no administrator rights on the device.
  """

  @doc "Shown above the steps."
  def intro,
    do:
      "証明書ファイルとパスワードは管理者から配布されます（お使いの端末に合わせた形式: Windows は .pfx、macOS と Android は .p12、iPhone / iPad は .mobileconfig）。いずれも端末の管理者権限なしでインストールできます。"

  @doc "Sections as {title, [step]} (plain text; the page escapes it)."
  def sections do
    [
      {"Windows（Chrome / Edge）",
       [
         "配布された .pfx ファイルをダブルクリックします（「証明書のインポート ウィザード」が開きます）。",
         "「保存場所」は「現在のユーザー」を選び、「次へ」を押します（「ローカル コンピューター」は管理者権限が必要なので選びません）。",
         "ファイル名はそのまま「次へ」。パスワードの欄に、別途伝えられたパスワードを入力して「次へ」を押します（「このキーをエクスポート可能にする」にはチェックしないでください）。",
         "「証明書の種類に基づいて、自動的に証明書ストアを選択する」のまま「次へ」→「完了」を押します。",
         "ブラウザ（Chrome / Edge）をすべて閉じてから開き直し、AskDrive を開きます。証明書の選択画面が出たら「AskDrive（グループ名）」を選んで「OK」を押します。"
       ]},
      {"macOS（Safari / Chrome / Edge）",
       [
         "配布された .p12 ファイルをダブルクリックします（「キーチェーンアクセス」が開きます）。",
         "追加先のキーチェーンは「ログイン」を選び（「システム」は管理者権限が必要なので選びません）、別途伝えられたパスワードを入力します。",
         "ブラウザを終了してから開き直し、AskDrive を開きます。証明書の選択画面が出たら「AskDrive（グループ名）」を選びます。",
         "「キーチェーンの使用を許可しますか」と表示されたら、Mac のログインパスワードを入力して「常に許可」を押します。"
       ]},
      {"iPhone / iPad（Safari）",
       [
         ".mobileconfig ファイルを AirDrop・メール・「ファイル」アプリなどで端末に送り、タップして開きます（「プロファイルがダウンロードされました」と表示されます）。",
         "「設定」アプリを開き、上部の「プロファイルがダウンロード済み」（または「一般」→「VPN とデバイス管理」）をタップします。",
         "「インストール」を押し、端末のパスコード、続けて別途伝えられた証明書のパスワードを入力して、インストールを完了します（「未検証」と表示されますが、AskDrive が作成したプロファイルのため問題ありません）。",
         "Safari で AskDrive を開きます。証明書の選択を求められたら「AskDrive（グループ名）」を選びます。"
       ]},
      {"Android（Chrome）",
       [
         ".p12 ファイルを端末に保存します（メールの添付などからダウンロード）。画面ロック（PIN・パターン等）が未設定の場合は、インストール時に設定を求められます。",
         "「設定」→「セキュリティとプライバシー」→「その他のセキュリティ設定」→「暗号化と認証情報」→「証明書のインストール」→「VPN とアプリのユーザー証明書」を開きます（メニューの名前は機種や Android のバージョンで異なります。設定の検索で「証明書」と探すと見つかります）。",
         "保存した .p12 ファイルを選び、別途伝えられたパスワードを入力します。証明書の名前は「AskDrive」など分かりやすいものにします。",
         "Chrome で AskDrive を開きます。証明書の選択を求められたら「AskDrive」を選んで「選択」を押します。"
       ]},
      {"Firefox（Windows / macOS）",
       [
         "Firefox は OS とは別に証明書を管理します。「設定」→「プライバシーとセキュリティ」→「証明書」の「証明書を表示...」を開きます。",
         "「あなたの証明書」タブで「インポート...」を押し、.p12 ファイルを選んで、別途伝えられたパスワードを入力します。",
         "Firefox を開き直し、AskDrive を開きます。証明書の選択を求められたら「AskDrive（グループ名）」を選びます。"
       ]},
      {"うまくいかないとき",
       [
         "インストール後も表示が変わらない場合は、ブラウザを完全に終了してから開き直してください（ブラウザは証明書の選択を覚えています）。",
         "証明書の選択画面で、別の証明書を選んでしまった場合も、ブラウザを開き直すと選び直せます。",
         "証明書を新しいものに交換した場合は、古い証明書を削除してから開き直してください（Windows:「ユーザー証明書の管理」、macOS:「キーチェーンアクセス」、iPhone:「VPN とデバイス管理」、Android:「ユーザー認証情報」）。",
         "「失効しています」「有効期限が切れています」と表示された場合は、新しい証明書を管理者に依頼してください。"
       ]}
    ]
  end
end
